import PDFDocument from "pdfkit";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOPS_DIR = path.join(__dirname, "..", "uploads", "sops");

const BRAND = "#1a2b4a";
const ACCENT = "#c8a24a";
const LIGHT = "#f4f6fa";

const FILES = [
  { txt: "client-leave-policy-template.txt", pdf: "Leave-Policy-SOP-Template.pdf", title: "Leave Policy SOP" },
  { txt: "client-recruitment-sop-template.txt", pdf: "Recruitment-SOP-Template.pdf", title: "Recruitment SOP" },
  { txt: "client-onboarding-sop-template.txt", pdf: "Employee-Onboarding-SOP-Template.pdf", title: "Employee Onboarding SOP" },
  { txt: "client-payroll-attendance-sop-template.txt", pdf: "Payroll-Attendance-SOP-Template.pdf", title: "Payroll & Attendance SOP" },
  { txt: "client-performance-sop-template.txt", pdf: "Performance-Management-SOP-Template.pdf", title: "Performance Management SOP" },
];

const PAGE_W = 595.28;
const PAGE_H = 841.89;
const M = 50;
const CW = PAGE_W - M * 2;
const BOTTOM = PAGE_H - 60;

function drawHeader(doc, title) {
  doc.rect(0, 0, PAGE_W, 70).fill(BRAND);
  doc.rect(0, 70, PAGE_W, 3).fill(ACCENT);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(16).text(title, M, 20, { width: CW });
  doc.font("Helvetica-Bold").fontSize(8).fillColor(ACCENT).text("EDITABLE SAMPLE FORMAT - STANDARD OPERATING PROCEDURE", M, 44, { width: CW });
}

function drawFooter(doc) {
  doc.rect(0, PAGE_H - 26, PAGE_W, 26).fill(BRAND);
  doc.font("Helvetica").fontSize(7.5).fillColor("#c9d4e5").text(
    "Replace all [bracketed] placeholders with your organisation's values.  |  Generated by HRMS SOP Library",
    M, PAGE_H - 18, { width: CW, align: "center" }
  );
}

function convert({ txt, pdf, title }) {
  const raw = fs.readFileSync(path.join(SOPS_DIR, txt), "utf8");
  const lines = raw.split(/\r?\n/);

  const doc = new PDFDocument({ margin: 0, size: "A4" });
  const out = fs.createWriteStream(path.join(SOPS_DIR, pdf));
  doc.pipe(out);

  drawHeader(doc, title);
  drawFooter(doc);
  let y = 90;

  const ensureSpace = (h) => {
    if (y + h > BOTTOM) {
      doc.addPage({ margin: 0, size: "A4" });
      drawHeader(doc, title);
      drawFooter(doc);
      y = 90;
    }
  };

  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    // Skip the plain-text banner block (==== lines and centered title lines at top)
    if (/^=+$/.test(trimmed)) { i++; continue; }
    if (i < 6 && (trimmed === "" || /^[A-Z\[\] &'-]+$/.test(trimmed))) { i++; continue; }
    // Skip divider rules
    if (/^-{10,}$/.test(trimmed)) { i++; continue; }
    if (trimmed === "--- END OF DOCUMENT ---" || trimmed.startsWith("(Replace all")) { i++; continue; }

    if (trimmed === "") { y += 6; i++; continue; }

    // Table block: consecutive lines starting with |
    if (trimmed.startsWith("|")) {
      const tbl = [];
      while (i < lines.length && lines[i].trim().startsWith("|")) {
        const cells = lines[i].trim().split("|").slice(1, -1).map((c) => c.trim());
        // skip separator rows like |---|---|
        if (!cells.every((c) => /^-*$/.test(c))) tbl.push(cells);
        i++;
      }
      if (tbl.length === 0) continue;
      const cols = Math.max(...tbl.map((r) => r.length));
      const colW = CW / cols;
      tbl.forEach((row, ri) => {
        const rowH = 18;
        ensureSpace(rowH);
        const isHead = ri === 0;
        if (isHead) doc.rect(M, y, CW, rowH).fill(BRAND);
        else if (ri % 2 === 0) doc.rect(M, y, CW, rowH).fill(LIGHT);
        doc.font(isHead ? "Helvetica-Bold" : "Helvetica").fontSize(8).fillColor(isHead ? "#ffffff" : "#222222");
        row.forEach((cell, ci) => {
          doc.text(cell, M + ci * colW + 4, y + 5, { width: colW - 8, height: rowH, ellipsis: true });
        });
        y += rowH;
      });
      y += 8;
      continue;
    }

    // Section heading: "1. PURPOSE", "DOCUMENT CONTROL", "REVISION HISTORY"
    if (/^(\d+\.\s+[A-Z]|DOCUMENT CONTROL|REVISION HISTORY)/.test(trimmed) && trimmed === trimmed.toUpperCase()) {
      ensureSpace(30);
      y += 6;
      doc.rect(M, y - 3, CW, 20).fill(LIGHT);
      doc.rect(M, y - 3, 3, 20).fill(ACCENT);
      doc.font("Helvetica-Bold").fontSize(10.5).fillColor(BRAND).text(trimmed, M + 10, y + 1, { width: CW - 14 });
      y += 24;
      i++;
      continue;
    }

    // Key : value line (document control block)
    if (/^[A-Za-z ()/&-]+ {2,}: /.test(line) || /^[A-Za-z ()/&-]+\s+:\s/.test(trimmed)) {
      const idx = trimmed.indexOf(":");
      const k = trimmed.slice(0, idx).trim();
      const v = trimmed.slice(idx + 1).trim();
      ensureSpace(14);
      doc.font("Helvetica-Bold").fontSize(9).fillColor("#333333").text(k, M, y, { width: 170, continued: false });
      doc.font("Helvetica").fontSize(9).fillColor("#222222").text(v, M + 175, y, { width: CW - 175 });
      y += 14;
      i++;
      continue;
    }

    // Regular paragraph / list line
    doc.font("Helvetica").fontSize(9.5).fillColor("#222222");
    const h = doc.heightOfString(trimmed, { width: CW, lineGap: 2 });
    ensureSpace(h + 2);
    doc.text(trimmed, M, y, { width: CW, lineGap: 2 });
    y += h + 3;
    i++;
  }

  doc.end();
  return new Promise((resolve) => out.on("finish", () => resolve(pdf)));
}

for (const f of FILES) {
  const name = await convert(f);
  console.log("Generated:", name);
}
console.log("Done.");
